A("Passive buy-and-hold over the traded windows was positive on five of the six")
A("symbol-by-timeframe windows (the exception is SUI five-minute). Every strategy")
A("cell loses in ABSOLUTE terms, so the verdict does not depend on the passive")
A("comparison — these books wipe out while passive mostly rises.")
A("")
A("## Artifacts and verification")
A("")
A("One hundred twenty artifacts in `results/runs/`, each sha-bound to the engine,")
A("the kline CSV and the funding JSON, cut at the creation day. Bit-for-bit")
A("verification: `results/_scalpma20_verify.txt`. Machine-readable matrix:")
