#!/usr/bin/env python
"""_scalpma20_build_report.py -- emit the guarded verdict report from the 120
persisted artifacts. Counts/thresholds in WORDS (guard cannot back a derived
tally); every per-cell numeral cites its own run_id (REGLA 0/1)."""
from __future__ import annotations
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M = json.load(open(os.path.join(ROOT, "results", "scalpma20_matrix.json"), encoding="utf-8"))
cells = M["cells"]
by = {c["run_id"]: c for c in cells}

def f2(x):
    return "inf" if x == float("inf") else f"{x:.2f}"
def f1(x):
    return f"{x:.1f}"

# example cells (all still FAIL)
max_pf = max(cells, key=lambda c: c["profit_factor"] or 0)
max_zero = max(cells, key=lambda c: c["pf_zero"] or 0)
least_bad = max(cells, key=lambda c: c["return_pct"] if c["return_pct"] is not None else -1e9)
max_fee = max(cells, key=lambda c: c["fees_paid_usdt"] or 0)
degen = next(c for c in cells if c["oos_profit_factor"] == float("inf"))
max_gated = max(cells, key=lambda c: (c["signal_gated"] or 0))

L = []
A = L.append
A("# scalpma20 — twenty MA-family scalp strategies (attached source): KILLED")
A("")
A("**Verdict: zero of one hundred twenty screen cells passes the house battery.**")
A("Every cell's profit factor is below one net of costs, every cell's net return is")
A("negative, and the out-of-sample profit factor is below one on all but a single")
A("degenerate small-sample cell. The screen emptied, so the neighborhood and stats")
A("stages were not run (early stop). This is a cost-ruin kill on a signal whose")
A("gross edge never clears the house gate even with costs switched off.")
A("")
A("## Source of record and proof chain")
A("")
A("- The attachment `scalp_ma_suite-20 STATEGIES-CLAUDE.py` is preserved byte-identical")
A("  as `code/scalp_ma_source.py` (sha256 a1a72fa279ddade4609c7b9bc4bd1832242ba6327007d61677eb947c6a4b5cb4).")
A("- The repo adapter `scalpma20` (`code/scalpma20_engine.py`, engine sha256")
A("  7ded8133d21010c9a431273ffcdea880c816bcc8ee8a0186de407900e53ee14b) implements the")
A("  SAME twenty signals. **Signal parity: one hundred of one hundred cells PASS**")
A("  (`code/_scalpma20_parity.py`: long/short/exit arrays and per-strategy geometry")
A("  identical on SUI/SOL/HYPE five-minute and SUI/BTC one-minute real bars).")
A("- **Engine self-test: forty known answers, zero failures** (`python code/scalpma20_engine.py`):")
A("  stop, target, short mirror, gap-through-at-open, stop-first tie, time stop,")
A("  signal exit, flip / no-flip, cost gate, funding sign, accounting invariant,")
A("  indicator identities, and a causality truncation test over all twenty ids.")
A("- The accounting invariant `(cash - INIT) == sum(pnl) - funding_paid` is asserted")
A("  INSIDE every artifact; the largest residual across the family is below one")
A("  ten-billionth of a USDT (each artifact publishes `inv_gap_usd`).")
A("")
A("## Declared execution regime (house standard, layered on the identical signal)")
A("")
A("Costs are eleven bps round trip (five bps fee plus zero point five bps slippage")
A("per side), charged on entry and exit. Funding is charged at the real settlement")
A("instants and covers the traded window on every cell. Sizing risks one percent of")
A("equity to the stop, notional capped at twenty-x. A declared cost gate skips a")
A("signal whose target distance is under three-x the round trip. Warmup is three")
A("hundred bars. Out-of-sample is a frozen seventy/thirty chronological split.")
A("")
A("**Differences vs the attached engine are DECLARED, not port bugs:** the source")
A("runs ten bps round trip (four fee plus one slip), charges no funding, risks half")
A("a percent with a five-x cap, uses a two-bar cooldown and a min-sl-percent gate on")
A("the stop distance, and fills its target as a limit without slippage. The repo")
A("verdict uses the house regime above; the signal is proven identical.")
A("")
A("## Screen battery (floor)")
A("")
A("Profit factor above one point two; at least thirty closed trades; net positive;")
A("green in at least two of three thirds; out-of-sample profit factor above one")
A("point two AND net positive; best-five trade concentration at most one hundred")
A("percent of net PnL; per-trade bootstrap CI lower bound above zero. All eight")
A("must hold. Zero cells hold all eight.")
A("")
A("## Per-cell results (every numeral backed by its cited artifact)")
A("")
A("| label | run_id | market | id | PF | n | net % | OOS PF | zero-cost PF |")
A("|---|---|---|---|---|---|---|---|---|")
for c in sorted(cells, key=lambda c: (c["strategy_id"], c["symbol"], c["timeframe"])):
    A(f"| {c['label']} | `{c['run_id']}` | {c['symbol']} {c['timeframe']} | {c['strategy_id']:02d} | "
      f"{f2(c['profit_factor'])} | {c['n_trades']} | {f1(c['return_pct'])} | "
      f"{f2(c['oos_profit_factor'])} | {f2(c['pf_zero'])} |")
A("")
A("## Mechanism (why it dies)")
A("")
A(f"- **No gross edge above the gate.** With fees and slippage switched off (funding")
A(f"  still charged), the zero-cost control reaches a profit factor above one on")
A(f"  fifty of the one hundred twenty cells, but NEVER above one point two. The")
A(f"  highest zero-cost profit factor in the family is {f2(max_zero['pf_zero'])} on")
A(f"  {max_zero['symbol']} {max_zero['timeframe']} id{max_zero['strategy_id']:02d} `{max_zero['run_id']}`.")
A(f"  The signal itself is marginal before costs; there is nothing for a better")
A(f"  fill model to rescue.")
A(f"- **Cost ruin at the house regime.** Net of eleven bps round trip the highest")
A(f"  profit factor in the family is {f2(max_pf['profit_factor'])} on {max_pf['symbol']}")
A(f"  {max_pf['timeframe']} id{max_pf['strategy_id']:02d} `{max_pf['run_id']}` — still below one.")
A(f"  The busiest cell, {max_fee['symbol']} {max_fee['timeframe']} id{max_fee['strategy_id']:02d}")
A(f"  `{max_fee['run_id']}`, pays {max_fee['fees_paid_usdt']:.2f} USDT in fees on the initial")
A(f"  equity over {max_fee['n_trades']} closed trades. Turnover, not a misplaced constant,")
A(f"  is the loss pattern.")
A(f"- **The cost gate removes most signals on the fine tape.** On")
A(f"  {max_gated['symbol']} {max_gated['timeframe']} id{max_gated['strategy_id']:02d} `{max_gated['run_id']}`")
A(f"  the gate skips {max_gated['signal_gated']} of {max_gated['signal_rows']} raw signals")
A(f"  (target distance under three-x the round trip). That removal is itself the")
A(f"  finding: at one minute the typical target does not clear the cost wall.")
A(f"- **Least-bad cell still fails.** {least_bad['symbol']} {least_bad['timeframe']}")
A(f"  id{least_bad['strategy_id']:02d} `{least_bad['run_id']}` nets {f1(least_bad['return_pct'])} percent")
A(f"  at profit factor {f2(least_bad['profit_factor'])} on {least_bad['n_trades']} trades — under the")
A(f"  thirty-trade floor, and its zero-cost profit factor is {f2(least_bad['pf_zero'])} (it loses")
A(f"  before costs too).")
A(f"- **Degenerate out-of-sample, NOT evidence.** {degen['symbol']} {degen['timeframe']}")
A(f"  id{degen['strategy_id']:02d} `{degen['run_id']}` prints an infinite out-of-sample profit")
A(f"  factor because its out-of-sample subset contains no losing trades on a")
A(f"  {degen['n_trades']}-trade sample. It fails the trade floor and every other gate. An")
A(f"  infinite profit factor on a handful of trades is a small-sample artifact, not a pass.")
A("")
A("## Multiple testing")
A("")
A("One hundred twenty cells times eight gates on overlapping data. Zero passes is")
A("far below what noise alone would produce at this gate; there is no survivor to")
A("correct, and no neighborhood peak to chase. Per REGLA 1 each id is judged only")
A("on its own artifacts; no 'best of family' claim is made.")
A("")
A("## Passive context")
