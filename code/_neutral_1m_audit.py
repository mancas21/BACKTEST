HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))

PAPER = os.path.join(HERE, "xrp_neutral_engine_paper.py")
DUAL = os.path.join(HERE, "xrp_neutral_engine_paper_1m.py")
BUILD = os.path.join(HERE, "_neutral_1m_build.py")
OUT = os.path.join(HERE, "_neutral_1m_audit.json")
K15 = os.path.join(ROOT, "data", "binance_klines_15m", "XRPUSDT_15m.csv")
