FUND = os.path.join(ROOT, "data", "binance_funding")

# the deployed paper config (neutral_paper_bot.py CONFIG + sizing)
PAPER_KW = dict(init=25.0, trend_band=0.10, stop_atr_mult=0.5, cover_mult=1.0,
                delta_max_pct=2.0, leg_fee=2.0 / 1e4, flat_fee=5.0 / 1e4,
                flat_slip=5.0 / 1e4, funding=True, fund_dir=FUND)

CHECKS = []


def check(name, ok, detail):
    CHECKS.append({"name": name, "pass": bool(ok), "detail": detail})
    print(("  PASS  " if ok else "  FAIL  ") + name, flush=True)
    if not ok:
        print("        " + json.dumps(detail, default=str)[:800], flush=True)


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    m.EQUITY_PCT = 1.0
    return m


def read_bars(path, start_ms=None, end_ms=None):
    rows = []
    with open(path, newline="") as f:
        for r in csv.DictReader(f):
            t = int(r["open_ts"])
            if start_ms is not None and t < start_ms:
                continue
            if end_ms is not None and t >= end_ms:
                continue
            rows.append((t, float(r["open"]), float(r["high"]), float(r["low"]),
                         float(r["close"]), float(r["volume"])))
    rows.sort(key=lambda b: b[0])
    return rows


def iso(ms):
    return (datetime.fromtimestamp(ms / 1000, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            if ms else None)


def eq_metrics(tr, init):
    eqc = np.asarray(tr["eq_curve"], float)
    pk = np.maximum.accumulate(eqc)
    mdd = float(np.max((pk - eqc) / np.maximum(pk, 1e-9)) * 100.0)
    return dict(n_bars_15m=len(eqc), profit_factor=None, n_trades=len(tr["trades"]),
                win_rate=None, return_pct=round(100.0 * (float(eqc[-1]) / init - 1.0), 2),
                max_dd_pct=round(mdd, 2), final_equity=round(float(eqc[-1]), 2))


def trade_key(t):
    return (int(t["dir"]), float(t["qty"]), float(t["entry"]), float(t["exit"]),
            float(t["cover"]), float(t["pnl"]), float(t["fees"]), str(t["reason"]),
            int(t["ts"]), int(t.get("entry_ts", 0)))


def compare_runs(a, b, a_name, b_name):
    """Exact comparison of everything the simulation produces."""
    diffs = []
    for k in ("eq_curve", "delta_curve", "gross_curve", "expo_curve"):
        if not np.array_equal(np.asarray(a[k]), np.asarray(b[k])):
            diffs.append(f"{k} differs")
    if len(a["trades"]) != len(b["trades"]):
        diffs.append(f"trade count {len(a['trades'])} vs {len(b['trades'])}")
    else:
        for i, (x, y) in enumerate(zip(a["trades"], b["trades"])):
            if trade_key(x) != trade_key(y):
                diffs.append(f"trade {i} differs: {trade_key(x)} vs {trade_key(y)}")
                break
    for k in ("grids", "fills", "cycles", "fund", "fees", "mdd", "open_lots",
              "max_abs_delta_pct", "max_delta_fill_pct", "delta_cap_hits",
              "stand_down_bars", "n_funding_events", "init"):
        if a[k] != b[k]:
            diffs.append(f"{k}: {a[k]} vs {b[k]}")
    if dict(a["reasons"]) != dict(b["reasons"]):
        diffs.append(f"reasons: {dict(a['reasons'])} vs {dict(b['reasons'])}")
    return diffs


# ── B. synthetic known-answer cases ─────────────────────────────────────────
def synth_bars(n=10, t0=1672531200000, base=100.0, hi=100.5, lo=99.5):
    return [(t0 + i * 900000, base, hi, lo, base, 1.0) for i in range(n)]


def write_tape(path, bar_ts, minutes):
    """minutes: list of (offset_min, low, high)."""
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["open_ts", "open", "high", "low", "close", "volume"])
        for off, lo, hi in minutes:
            w.writerow([bar_ts + off * 60000, (hi + lo) / 2.0, hi, lo,
                        (hi + lo) / 2.0, 1.0])


def run_case(dual, tape_path, bars):
    """One run on a fresh module state; NP_1M_CSV points at tape_path or ''."""
    if tape_path:
        os.environ["NP_1M_CSV"] = tape_path
    else:
        os.environ.pop("NP_1M_CSV", None)
    tr = {}
    dual.simulate(bars, "XRPUSDT", track=tr, init=1000.0,
                  trend_band=99.0, stop_atr_mult=0.5, cover_mult=1.0,
                  delta_max_pct=100.0, leg_fee=2.0 / 1e4, flat_fee=5.0 / 1e4,
                  leg_slip=0.0, flat_slip=0.0, funding=False)
    return tr


def prepare_synth(dual):
    # Make the geometry unambiguous and the fill prices hand-computable:
    # ATR=1 -> half=2 -> step=2 on center 100 -> long 98 cover 100, short 102.
    dual.GRID_LEVELS = 1
    dual.ATR_MULT = 2.0
    dual.ATR_PERIOD = 2
    dual.WARMUP_BARS = 1
    dual.REBUILD_DRIFT = 99.0
    dual.COOLDOWN_BARS = 0
    dual.TREND_BAND = 99.0


def test_ordering():
    # a FRESH module: prepare_synth mutates module globals, and those must not
    # leak into the full-history identity or reproduction runs.
    dual = load(DUAL, "np_paper_1m_ord")
    prepare_synth(dual)
    t0 = 1672531200000
    T5 = t0 + 5 * 900000
    bars = synth_bars()
    bars[5] = (T5, 100.0, 100.5, 97.9, 100.0, 1.0)   # touches BOTH 98 and 100
    A = [(i, 97.9 if i < 5 else 99.6, 99.4 if i < 5 else 100.5) for i in range(15)]
    B = [(i, 99.6 if i < 5 else 97.9, 100.5 if i < 5 else 99.4) for i in range(15)]
    C = [(0, 97.9, 100.5)] + [(i, 99.3, 99.4) for i in range(1, 15)]
    E = A[:14]                                        # partial: 14 of 15
    import copy
    bars6 = synth_bars()
    bars6[5] = bars[5]
    cases = {"A_entry_then_cover": A, "B_cover_before_entry": B,
             "C_same_minute": C, "E_partial_tape": E}

    tmp = tempfile.mkdtemp(prefix="np1m_")
    paths = {}
    for name, mins in cases.items():
        paths[name] = os.path.join(tmp, name + ".csv")
        write_tape(paths[name], T5, mins)

    trA = run_case(dual, paths["A_entry_then_cover"], bars6)
    trB = run_case(dual, paths["B_cover_before_entry"], bars6)
    trC = run_case(dual, paths["C_same_minute"], bars6)
    trD = run_case(dual, None, bars6)
    trE = run_case(dual, paths["E_partial_tape"], bars6)

    exp = {}

    # A: entry minute 0 -> cover minute 5, on the action bar.
    exp["A"] = (len(trA["trades"]) == 1 and trA["trades"][0]["ts"] == T5
                and trA["trades"][0]["entry_min_ts"] == T5
                and trA["trades"][0]["exit_min_ts"] == T5 + 5 * 60000
                and abs(trA["trades"][0]["entry"] - 98.0) < 1e-12
                and abs(trA["trades"][0]["exit"] - 100.0) < 1e-12
                and abs(trA["trades"][0]["pnl"] - 19.604) < 1e-9
                and trA["same_minute_touched"] == 0
                and trA["one_m_covers"] == 1 and trA["same_bar_covers"] == 0
                and trA["bars_resolved"] == 1)
    # B: cover touch (minutes 0-4) precedes the entry (minute 5); no cover on
    #    the action bar, so the lot exits on the NEXT (fallback) bar.
    exp["B"] = (len(trB["trades"]) == 1 and trB["trades"][0]["ts"] == T5 + 900000
                and trB["trades"][0]["entry_min_ts"] == T5 + 5 * 60000
                and trB["trades"][0]["exit_min_ts"] == -1
                and abs(trB["trades"][0]["entry"] - 98.0) < 1e-12
                and abs(trB["trades"][0]["exit"] - 100.0) < 1e-12
                and trB["one_m_covers"] == 0 and trB["same_bar_covers"] == 0)
    # C: entry and cover in the SAME minute -> banned and counted; the lot
    #    stays open and exits on the next fallback bar.
    exp["C"] = (len(trC["trades"]) == 1 and trC["trades"][0]["ts"] == T5 + 900000
                and trC["same_minute_touched"] == 1
                and trC["one_m_covers"] == 0 and trC["same_bar_covers"] == 0)
    # D: no tape -> the original same-bar model, same-bar cover counted.
    exp["D"] = (len(trD["trades"]) == 1 and trD["trades"][0]["ts"] == T5
                and trD["trades"][0]["entry_min_ts"] == -1
                and trD["trades"][0]["exit_min_ts"] == -1
                and trD["same_bar_covers"] == 1 and trD["one_m_covers"] == 0
                and trD["bars_no_tape"] == 10 and trD["bars_resolved"] == 0)
    # E: 14 minutes is NOT a complete tape -> fallback, counted as partial.
    exp["E"] = (len(trE["trades"]) == 1 and trE["trades"][0]["ts"] == T5
                and trE["same_bar_covers"] == 1
                and trE["bars_partial"] == 1 and trE["bars_resolved"] == 0)

    check("B case A: entry minute then cover minute fills on the bar", exp["A"],
          {"trades": trA["trades"][:1], "same_minute": trA["same_minute_touched"],
           "one_m_covers": trA["one_m_covers"], "resolved": trA["bars_resolved"]})
    check("B case B: cover touch BEFORE entry does not fill on that bar", exp["B"],
          {"trades": trB["trades"][:1], "one_m_covers": trB["one_m_covers"]})
    check("B case C: same-minute touch is banned and counted", exp["C"],
          {"trades": trC["trades"][:1], "same_minute": trC["same_minute_touched"]})
    check("B case D: no tape keeps the original same-bar cover", exp["D"],
          {"trades": trD["trades"][:1], "same_bar_covers": trD["same_bar_covers"]})
    check("B case E: 14/15 minutes is partial and falls back", exp["E"],
          {"trades": trE["trades"][:1], "partial": trE["bars_partial"]})

    # the falsification: identical 15m OHLC, different tape order -> different bar
    check("B order matters: A and B share OHLC but exit on different bars",
          trA["trades"][0]["ts"] == T5 and trB["trades"][0]["ts"] == T5 + 900000,
          {"A_exit_bar": iso(trA["trades"][0]["ts"]),
           "B_exit_bar": iso(trB["trades"][0]["ts"])})

    for p in paths.values():
        os.unlink(p)
    os.rmdir(tmp)


# ── C. published kill reproduction ──────────────────────────────────────────
def test_reproduction(base, dual):
    expected = json.load(open(os.path.join(HERE, "_xrp_1m_resolution_out.json"),
                              encoding="utf-8"))
    start = 1672531200000                       # 2023-01-01T00:00Z
    end = int(datetime(2026, 10, 1, 13, 45, tzinfo=timezone.utc).timestamp() * 1000)
    bars = read_bars(K15, start, end)
    os.environ.pop("NP_1M_CSV", None)

    def run(mod):
        tr = {}
        mod.simulate(bars, "XRPUSDT", track=tr, **PAPER_KW)
        cp = np.asarray(tr["closed_pnl"], float)
        pf, win, n = mod.metrics(list(cp))
        m = eq_metrics(tr, 25.0)
        m.update(profit_factor=round(float(pf), 4), win_rate=round(float(win), 2),
                 n_trades=int(n), same_minute_touched=int(tr.get("same_minute_touched", -1)))
        return tr, m

    tr_b, got_b = run(base)
    exp_b = expected["baseline_15m_model_2023plus"]
    ok_b = all([got_b["profit_factor"] == exp_b["profit_factor"],
                got_b["n_trades"] == exp_b["n_trades"],
                got_b["win_rate"] == exp_b["win_rate"],
                got_b["return_pct"] == exp_b["return_pct"],
                got_b["max_dd_pct"] == exp_b["max_dd_pct"],
                got_b["final_equity"] == exp_b["final_equity_usdt"]])
    check("C 15m baseline on the probe slice reproduces", ok_b,
          {"got": got_b, "expected": exp_b})

    os.environ["NP_1M_CSV"] = K1
    tr_1, got_1 = run(dual)
    os.environ.pop("NP_1M_CSV", None)
    exp_1 = expected["one_minute_resolved"]
    ok_1 = all([got_1["profit_factor"] == exp_1["profit_factor"],
                got_1["n_trades"] == exp_1["n_trades"],
                got_1["win_rate"] == exp_1["win_rate"],
                got_1["return_pct"] == exp_1["return_pct"],
                got_1["max_dd_pct"] == exp_1["max_dd_pct"],
                got_1["same_minute_touched"] == exp_1["same_minute_touched"],
                got_1["final_equity"] == exp_1["final_equity_usdt"]])
    check("C 1m-resolved result reproduces the published kill exactly", ok_1,
          {"got": got_1, "expected": exp_1})

    # completeness of the tape over the slice, measured inside the artifact
    n_used = tr_1["minutes_used"]
    ok_cov = (tr_1["bars_resolved"] == len(bars) and tr_1["bars_partial"] == 0
              and tr_1["bars_no_tape"] == 0 and n_used == 15 * len(bars))
    check("C every bar in the slice carries a complete 15-minute tape", ok_cov,
          {"bars": len(bars), "resolved": tr_1["bars_resolved"],
           "partial": tr_1["bars_partial"], "no_tape": tr_1["bars_no_tape"],
           "minutes_used": n_used})


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true",
                    help="skip the full-history and reproduction runs")
    args = ap.parse_args()

    import _neutral_1m_build as B
    sha, _ = B.build()
    print(f"rebuilt dual engine sha {sha}", flush=True)

    test_ordering()

    if not args.fast:
        # A. no-tape identity over the ENTIRE repo history
        base = load(PAPER, "np_paper_base_full")
        dual = load(DUAL, "np_paper_1m_full")
        bars = read_bars(K15)
        os.environ.pop("NP_1M_CSV", None)
        tr_b, tr_d = {}, {}
        base.simulate(bars, "XRPUSDT", track=tr_b, **PAPER_KW)
        dual.simulate(bars, "XRPUSDT", track=tr_d, **PAPER_KW)
        diffs = compare_runs(tr_b, tr_d, "paper", "dual")
        check("A no tape: dual engine is bit-identical to the 15m engine",
              not diffs, {"diffs": diffs[:5], "bars": len(bars),
                          "trades": len(tr_d["trades"])})
        ok_meta = all(t["entry_min_ts"] == -1 and t["exit_min_ts"] == -1
                      for t in tr_d["trades"])
        check("A no tape: every trade carries minute metadata = -1", ok_meta,
              {"trades": len(tr_d["trades"])})

        # A2. a tape that starts late must leave the prefix untouched
        late = int(datetime(2026, 9, 29, tzinfo=timezone.utc).timestamp() * 1000)
        fd, tmp = tempfile.mkstemp(suffix="_1m_tail.csv")
        os.close(fd)
        n_rows = 0
        with open(K1, newline="") as f, open(tmp, "w", newline="") as g:
            r = csv.reader(f)
            w = csv.writer(g)
            w.writerow(next(r))
            for row in r:
                if int(row[0]) >= late:
                    w.writerow(row)
                    n_rows += 1
        bars_t = read_bars(K15, None, int(datetime(2026, 10, 1, 13, 45,
                                                   tzinfo=timezone.utc).timestamp() * 1000))
        tr_tb, tr_td = {}, {}
        os.environ.pop("NP_1M_CSV", None)
        base.simulate(bars_t, "XRPUSDT", track=tr_tb, **PAPER_KW)
        os.environ["NP_1M_CSV"] = tmp
        dual.simulate(bars_t, "XRPUSDT", track=tr_td, **PAPER_KW)
        os.environ.pop("NP_1M_CSV", None)
        first_res = tr_td["res_first_ts"]
        ix = next(i for i, b in enumerate(bars_t) if b[0] == first_res)
        prefix_ok = np.array_equal(np.asarray(tr_tb["eq_curve"])[:ix],
                                   np.asarray(tr_td["eq_curve"])[:ix])
        check("A2 a late tape leaves every earlier bar bit-identical", prefix_ok,
              {"tape_rows": n_rows, "first_resolved": iso(first_res),
               "prefix_bars": ix, "resolved_bars": tr_td["bars_resolved"],
               "no_tape": tr_td["bars_no_tape"]})
        os.unlink(tmp)

        test_reproduction(base, dual)

    ok = all(c["pass"] for c in CHECKS)
    out = {"generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
           "engine_sha256": sha, "pass": ok, "checks": CHECKS}
    json.dump(out, open(OUT, "w", encoding="utf-8"), indent=1, default=str)
    print(f"\n{'PASS' if ok else 'FAIL'} — wrote {os.path.relpath(OUT, ROOT)}")
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()
