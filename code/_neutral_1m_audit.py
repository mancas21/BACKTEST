#!/usr/bin/env python3
"""_neutral_1m_audit.py — known-answer audit for the dual-mode 1m paper engine.

code/xrp_neutral_engine_paper_1m.py is GENERATED by code/_neutral_1m_build.py
from code/xrp_neutral_engine_paper.py, the byte-identical copy of the engine the
live 5-pair paper book runs on the VPS (sha256 834f3de9...). This audit proves
three things, in order of what could silently break the live record:

  A. NO-TAPE IDENTITY. With NP_1M_CSV unset, the variant must be bit-identical
     to the 15m paper engine: same equity curve, same trades, same counters.
     A2 repeats it with a tape that starts near the end of the series and
     asserts the pre-tape prefix is untouched, which is the property the live
     runner relies on: the day-0 baseline cannot move.

  B. ORDERING KNOWN-ANSWER CASES. Hand-built 15m bars with hand-built 1m tapes,
     where the sequence of touches inside the bar is known:
       * entry minute before cover minute  -> cover on that bar, exit minute set;
       * cover touch before the entry      -> no cover on that bar, cover later;
       * entry and cover in the SAME minute-> banned, counted, lot stays open;
       * no tape                           -> original same-bar cover;
       * partial tape (14 of 15 minutes)   -> fallback, counted as partial.
     Cases with the SAME 15m OHLC but different tape order must disagree: that
     is the falsification of "the bar model is good enough".

  C. PUBLISHED KILL REPRODUCTION. On the repo XRP 1m tape and the exact slice
     and parameters of code/_xrp_1m_resolution.py (2023-01-01..
     2026-10-01 13:45, v2 sizing), the variant must reproduce the published
     1m numbers stored in code/_xrp_1m_resolution_out.json, and the 15m
     baseline of the same slice must reproduce its own. Exact-match on the
     published precision.

Usage:  python code/_neutral_1m_audit.py [--fast]
"""
