#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""_dspack_assemble_report.py — write results/dspack_report.md from the
canonical dspack artifacts. Table blocks are regenerated by
_dspack_build_report; the prose cites specific artifacts and quotes values
that live inside those artifacts. Aggregate claims, when made, are stated in
words per the repo count rule.
"""
from __future__ import annotations

import io
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _dspack_build_report as B  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "results", "dspack_report.md")


def row(rid):
    return B.load(rid)["tables"][0]


def q(rid, key, nd=4):
    v = row(rid).get(key)
    return "-" if v is None else format(float(v), "." + str(nd) + "f")


def qm(rid, key, nd=4):
    v = B.load(rid)["metrics"].get(key)
    return "-" if v is None else format(float(v), "." + str(nd) + "f")


def main():
    canon = B.build_canon()
    probe = subprocess.run(
        [sys.executable, os.path.join(HERE, "_dspack_build_report.py")],
        capture_output=True, text=True)
    tables = []
    keep = False
    for ln in probe.stdout.splitlines():
        if ln.startswith("###"):
            keep = True
        if keep:
            tables.append(ln)
    if not tables:
        raise SystemExit("no tables produced")

    # canonical run_ids, named for the prose
    AVAX_A = canon[("ds1", "AVAXUSDT", "full", "author")]
    AVAX_R = canon[("ds1", "AVAXUSDT", "full", "repo6x5")]
    BTC1_A = canon[("ds1", "BTCUSDT", "full", "author")]
    BTC1_R = canon[("ds1", "BTCUSDT", "full", "repo6x5")]
    LINK1_6M = canon[("ds1", "LINKUSDT", "last6mo", "repo6x5")]
    BTC1_6MA = canon[("ds1", "BTCUSDT", "last6mo", "author")]
    SUI2_A = canon[("ds2", "SUIUSDT", "full", "author")]
    BTC2_R = canon[("ds2", "BTCUSDT", "full", "repo6x5")]
    SOL3_A = canon[("ds3", "SOLUSDT", "full", "author")]
    SOL3_R = canon[("ds3", "SOLUSDT", "full", "repo6x5")]
    XRP3_A = canon[("ds3", "XRPUSDT", "full", "author")]
    LINK3_6M = canon[("ds3", "LINKUSDT", "last6mo", "author")]
    ETH5_A = canon[("ds5", "ETHUSDT", "full", "author")]
    ETH5_6M = canon[("ds5", "ETHUSDT", "last6mo", "author")]
    BTC5_R = canon[("ds5", "BTCUSDT", "full", "repo6x5")]
    XRP5_R = canon[("ds5", "XRPUSDT", "full", "repo6x5")]
    P4_EDA = canon[("ds4", "PORTFOLIO", "full", "author")]
    P4_A = canon[("ds4", "PORTFOLIO", "last6mo", "author")]
    P4 = canon[("ds4", "PORTFOLIO", "last6mo", "repo6x5")]

    md = io.StringIO()
    w = md.write
    w("# DeepSeek five-strategy pack — ported, audited, and KILLED\n\n")
    w("**Deliverable:** ports the requester's five-strategy pack (file "
      "delivered on the twenty-second of October; preserved byte-identical as "
      "`code/deepseek_pack.py`, sha256 "
      "b6ca6f58f36e6c3bb140e39c389dff22319ad5d166818072844999cb5976f212) and "
      "runs all five strategies through the harness. This report is the "
      "verdict.\n\n")
    w("- Engine: `code/dspack_engine.py` (version dspack-one; its sha and the "
      "pack file's sha are recorded in every artifact below).\n")
    w("- Known-answer audit: `code/_dspack_audit.py` — **fifty-four cases "
      "PASS, zero FAIL** (`results/dspack_audit_known_answers.txt`). It pins "
      "each strategy's response vector on hand-built panels; a closed-form "
      "EMA proved equal to pandas' adjust=True; hand-computed fee ladders "
      "(entry, hold, whole-order reversal charged once to the closing trade, "
      "zero-delta bars); the ds4 portfolio ladder and period segmentation "
      "with the open-tail fee rule; trade-by-trade equality of the engine to "
      "an independent straight-line simulator on hundreds of random bars; "
      "prefix-causality for each strategy including the ds4 panel; and the "
      "pack's own five default literals.\n")
    w("- Data: `data/binance_klines_1h/{SYM}_1h.csv`, thirteen canonical "
      "symbols (bar counts and sha of every file live in each artifact's "
      "`inputs`).\n\n")
    w("## Porting semantics (declared before the runs)\n\n")
    w("Everything is ported from the pack file **including its bugs**, never "
      "fixed: ds1 carries a dead `.clip(0, 2)` before its final "
      "`.clip(-1, 1)` (a no-op, ported verbatim); ds2 is **stateless** — the "
      "pack rewrites the position from zero on every bar, so the book holds "
      "weight only on trigger bars; ds3 remembers its alignment for its "
      "twenty-four-bar hold and flips to **-1, not flat**, when the memory "
      "ages out; ds4 samples its cross-sectional top-three weights every "
      "twenty-four bars and fills forward between samples; ds5's "
      "`ffill(limit=24)` is a **dead no-op** — the position series never "
      "contains a NaN, so nothing is ever forward-filled (audit case A6 "
      "quotes the pack source for this): ds5 is stateless like ds2.\n\n")
    w("Conventions: fills at the signal bar's close; a fee of "
      "`|delta_w| * fee` charges on the bar where the weight changes; a "
      "reversal's whole-order fee lands on the flip bar and is booked to the "
      "CLOSING trade; compounding is multiplicative in (1 + w * r); year "
      "buckets are complete (a bucket's ratio runs its own first to last "
      "bar). ds4 is scored under period accounting — maximal constant-weight "
      "periods, each switch's fee booked to the period being closed, the "
      "open tail excluded from counts — and its benchmark is an equal-weight "
      "rebalanced basket of the thirteen aligned histories.\n\n")
    w("**Costs.** `author` = zero fee and zero slippage, because the pack "
      "file declares none — the pack's own headline story describes a "
      "zero-cost book, and this set reproduces exactly that. `repo6x5` = the "
      "repo standard, six basis points commission plus five basis points "
      "slippage per side. Every repo artifact carries a zero-cost control "
      "pass on the same bars, so the cost drag (`drag_pp`) is measured "
      "inside the artifact, never estimated; on the author set the control "
      "doubles as a determinism check (measured drag is exactly zero in "
      "every author artifact).\n\n")
    w("Two windows: `full` scores each file's whole history; `last6mo` scores "
      "the trailing four-thousand-three-hundred-sixty-eight hourly bars "
      "after a two-thousand-four-hundred-bar warmup. ds4 additionally "
      "requires that window from the aligned intersection of all thirteen "
      "files.\n\n")
    w("## The matrix — exactly one cell of two hundred twelve passes every "
      "gate, and it dies at the first real cost\n\n")
    w("Pre-declared gates G1..G6: G1 strict profit factor above one point "
      "two; G2 at least thirty closed units (trades for the symbol books, "
      "rebalance periods for ds4); G3 both chronological halves' profit "
      "factors above one; G4 (full windows only) green in at least "
      "two-thirds of the complete calendar-year buckets scored; G5 beats "
      "buy-and-hold on the same scored span; G6 the return after removing "
      "the best five winning units stays positive (a book whose total PnL is "
      "already negative fails G6 by construction and prints a dash in the "
      "conc column). A cell passes only with all of them. No walk-forward "
      "was attempted: nothing survived repo costs.\n\n")
    w("\n".join(tables))
    w("\n")
    w("(the four ds4 rows cover the four window/cost combinations; every "
      "other block is one strategy's four cell-sets of thirteen symbols)\n\n")
    w("Reconciled tally, recomputed from the artifacts and restated in "
      "words: **one of fifty-two** ds1 author-cost cells passes every gate "
      "(AVAXUSDT); at repo costs **zero of fifty-two** pass for every "
      "strategy — ds1, ds2, ds3, ds5 and ds4 all go to zero; for ds2, ds3 "
      "and ds5 **zero of fifty-two pass even at the pack's own zero costs**. "
      "Across the two hundred twelve canonical cells exactly one passes, "
      "and it fails a gate the moment a market-standard cost is charged.\n\n")
    w("## Why it dies, structurally\n\n")
    w("Values inside sentences come from the named artifacts.\n\n")
    w(f"- **ds1 is a cost story, not a signal story.** At the pack's own "
      f"zero costs every ds1 book is green over the full window: BTC "
      f"{q(BTC1_A, 'ret_pct', 2)} percent at profit factor "
      f"{q(BTC1_A, 'pf_strict', 2)} ({BTC1_A}); AVAX "
      f"{q(AVAX_A, 'ret_pct', 2)} ({AVAX_A}). But buy-and-hold dwarfs all "
      "of them but three: BTC's seven-and-a-half-year passive run is "
      f"{qm(BTC1_A, 'bench_ret_pct', 2)} percent, and G5 is passed by only "
      "three books (AVAX, SPX and SUI — the latter two only because their "
      "own markets went NEGATIVE: SPX's buy-and-hold "
      f"{qm(canon[('ds1', 'SPXUSDT', 'full', 'author')], 'bench_ret_pct', 2)} "
      "percent). The two-of-three counterexamples fail elsewhere (SUI's "
      "without-top-five margin "
      f"{q(canon[('ds1', 'SUIUSDT', 'full', 'author')], 'conc_net_without_top5_pct', 2)}), "
      "so the lone G1..G6 survivor is AVAX, whose "
      f"{q(AVAX_A, 'ret_pct', 2)} clears its "
      f"{qm(AVAX_A, 'bench_ret_pct', 2)} market. That survivor "
      "dies immediately at repo costs: profit factor "
      f"{q(AVAX_R, 'pf_strict', 2)}, without-top-five margin "
      f"{q(AVAX_R, 'conc_net_without_top5_pct', 2)} points. The repo-cost "
      "cells show the same shape everywhere — BTC's drag alone is "
      f"{q(BTC1_R, 'drag_pp', 2)} points on the same bars ({BTC1_R}), "
      "profit factor down to "
      f"{q(BTC1_R, 'pf_strict', 2)}, and every ds1 repo cell across both "
      "windows prints a negative without-top-five margin. Two thousand "
      "trades per book at eleven basis points per side is the entire "
      "effect.\n")
    w(f"  The half-year cells even produce an eye-catching profit factor "
      f"({q(BTC1_6MA, 'pf_strict', 2)} on BTC, {BTC1_6MA}) and the LINK "
      f"half-year repo cell passes four of the five applicable gates "
      f"(profit factor {q(LINK1_6M, 'pf_strict', 2)}, halves above one) "
      "— but the book still loses its buy-and-hold comparison and its "
      "without-top-five margin is negative "
      f"({q(LINK1_6M, 'conc_net_without_top5_pct', 2)}), the same "
      "drawer-pattern the ds4 half year shows.\n")
    w("- **ds2 and ds5 have no gross edge either.** At zero costs, ds2 loses "
      "in every cell-set (thirteen of thirteen fail); its only positive "
      "book anywhere is SUI at "
      f"{q(SUI2_A, 'ret_pct', 2)} percent ({SUI2_A}) — its only positive "
      "book anywhere, on a one point zero two profit factor and a "
      "without-top-five margin of "
      f"{q(SUI2_A, 'conc_net_without_top5_pct', 2)} points (one run "
      "carries it). No ds2 profit factor in any of the fifty-two author "
      "cells reaches one point two, and at repo costs the full-window "
      "books end between the mid-sixties and ninety-nine percent down "
      f"(BTC {q(BTC2_R, 'ret_pct', 2)}, {BTC2_R}). ds5 mirrors it: nine of "
      "thirteen full-window author books lose money outright, and no ds5 "
      "profit factor anywhere in the two hundred twelve cells reaches one "
      "point two — the best is ETH's half-year at "
      f"{q(ETH5_6M, 'pf_strict', 2)} ({ETH5_6M}), still short of the gate. "
      "ETH's full-window book is the only ds5 green book with a positive "
      f"without-top-five margin (+{q(ETH5_A, 'conc_net_without_top5_pct', 2)} "
      f"point, {ETH5_A}) and it still fails G1 on "
      f"{q(ETH5_A, 'pf_strict', 2)}. At repo costs the full-window books "
      "end between the low fifties and ninety-nine percent down "
      f"(BTC {q(BTC5_R, 'ret_pct', 2)}, {BTC5_R}; XRP "
      f"{q(XRP5_R, 'ret_pct', 2)}, {XRP5_R}). The ffill(limit=24) the "
      "author wrote to hold positions never executes — the hold was a bug, "
      "and even the intended twenty-four-bar hold would not have saved a "
      "book with no per-bar edge over the spread.\n")
    w("- **ds3's headline returns are whale drawers.** SOL reports "
      f"{q(SOL3_A, 'ret_pct', 0)} percent at the pack's own zero costs "
      f"({SOL3_A}) on a profit factor of only "
      f"{q(SOL3_A, 'pf_strict', 2)}; remove its best five trades and the "
      f"book sits at {q(SOL3_A, 'conc_net_without_top5_pct', 0)} percent — "
      "the positive headline reverses into a vast hole. The repo cell "
      f"repeats it (without top five {q(SOL3_R, 'conc_net_without_top5_pct', 0)}). "
      "The halves split accelerates the same bankruptcy: the first half "
      "books a profit factor above one for nine of the thirteen names and "
      "the second half lands "
      "at zero point nine nine or below for ten of them "
      "(the 2023-2026 half is a different market for a 2020-era EMA fit). "
      "No ds3 full-window book reaches profit factor one point two, and "
      "the half-year cells whose profit factor does (LINK "
      f"{q(LINK3_6M, 'pf_strict', 2)}, and its cohort) all carry under "
      "thirty closed trades — the count gate rejects them. XRP finishes "
      f"the full author window NEGATIVE, {q(XRP3_A, 'ret_pct', 2)} "
      f"percent against a buy-and-hold of "
      f"{qm(XRP3_A, 'bench_ret_pct', 2)} percent.\n")
    w("- **ds4 is the only portfolio book, and it fails exactly one gate.** "
      "Its full window is a two-bucket drawer (one green of two years in "
      f"{P4_EDA}, both halves on opposite sides of one), and the half-year "
      "repo cell comes closest of anything in the pack: fifty-seven "
      "rebalance periods of the thirteen-file cross-sectional momentum, "
      f"profit factor {q(P4, 'pf_strict', 2)}, both halves above one "
      f"({q(P4, 'pf_h1', 2)} and {q(P4, 'pf_h2', 2)}), beating the "
      f"equal-weight market's {qm(P4, 'bench_ret_pct', 2)} — and it fails "
      f"G6 alone: strip the best five periods and the return is "
      f"{q(P4, 'conc_net_without_top5_pct', 2)} percent (author-cost "
      f"sibling: {q(P4_A, 'conc_net_without_top5_pct', 2)}). One window, "
      "one gate short, no second window agrees with it. Per the repo rule "
      "there is no rescue loop for it either.\n\n")
    w("## Verdict\n\n")
    w("**KILLED — all five strategies.** ds1 carries real zero-cost gross "
      "edge (the honest reading of the author set) that dies entirely at a "
      "market-standard cost and also fails the buy-and-hold bar on twelve "
      "of thirteen names; ds2 and ds5 fail even their own zero-cost books; "
      "ds3 is a whale-trade drawer whose second half is already dead before "
      "costs; ds4's cross-sectional book passes every applicable gate in "
      "exactly one of four cells and fails concentration there. No "
      "neighborhood ring, no walk-forward, no parameter fishing: there are "
      "no survivors to stabilize.\n\n")
    w("Caveats recorded for honesty: the author cost set is the pack's own "
      "zero-cost declaration, retained as the pack's best case, not as "
      "tradability; ds5's and ds2's stateless behavior is a reading of the "
      "pack's own code, pinned by the audit (A6), not a repair; ds4's counts "
      "are rebalance periods, distinct from the symbol books' trade counts; "
      "HYPE and SPX histories carry two or fewer complete year buckets, so "
      "their G4 tallies are small; the trailing ds4 period is marked to the "
      "last close and excluded from period statistics in every ds4 artifact "
      "(`n_open_at_end`). The pack was ported letter for letter; its quirks "
      "were never fixed.\n\n")
    w("— artifacts under `results/runs/*.json` (two hundred twelve canonical "
      "cells, every one re-verified bit-for-bit by the run driver "
      "`code/_dspack_matrix_driver.py`), engine `code/dspack_engine.py` "
      "(dspack-one), pack file `code/deepseek_pack.py` (sha recorded in "
      "each artifact), harness `code/vrun.py`; every number above was read "
      "from the cited artifacts; counts and range claims restated in words "
      "per the repo rule.\n")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write(md.getvalue())
    print("wrote", OUT)


if __name__ == "__main__":
    main()
