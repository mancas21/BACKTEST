ENGINE_VERSION = "fvgup-1"
START_EQ = 10_000.0
WINDOW_START = "2023-01-01"   # repo 1m coverage begins (BTC/ETH: 2023-01-01)
WINDOW_END = "2026-10-01"     # repo 1m coverage ends ~2026-10-01 05:49 UTC

CARDS = {
    "BTCFINE":   dict(symbol="BTCUSDT", tick_size=0.1,  use_sessions=True,  fine=True),
    "BTCCOARSE": dict(symbol="BTCUSDT", tick_size=0.1,  use_sessions=True,  fine=False),
    "BTCNOSESS": dict(symbol="BTCUSDT", tick_size=0.1,  use_sessions=False, fine=True),
    "ETHFINE":   dict(symbol="ETHUSDT", tick_size=0.01, use_sessions=True,  fine=True),
}


def _load_kline(path):
    df = pd.read_csv(path, usecols=[0, 1, 2, 3, 4, 5])
    df.columns = ["open_ts", "open", "high", "low", "close", "volume"]
    # pandas 3.0 PRESERVES the input unit (to_datetime(unit="ms") -> ms index)
    # while the pack's Timestamp.value / Timedelta.value arithmetic is in
    # NANOSECONDS: an ms index makes the fine-tape fill comparison
    # (t >= ready_ts) compare ms against a ready_ts 1000x larger and the book
    # never fills (measured: 0 trades with the fine engine). Normalize to ns.
    df.index = pd.DatetimeIndex(
        pd.to_datetime(df["open_ts"].values, unit="ms", utc=True)).as_unit("ns")
    return df.drop(columns=["open_ts"]).sort_index()


def _pf(pnls):
    gains = sum(x for x in pnls if x > 0)
    losses = -sum(x for x in pnls if x < 0)
    if losses == 0:
        return None if gains == 0 else gains
    return gains / losses


def _finite(v):
    if v is None:
        return None
    v = float(v)
    return v if np.isfinite(v) else None


def run(paths, params):
    p = dict(params)
    card = str(p.pop("card", "")).upper()
    if card not in CARDS:
        raise ValueError(f"unknown fvgup card: {card!r} (use {sorted(CARDS)})")
    if p:
        raise ValueError(f"unknown fvgup params: {sorted(p)}")
    spec = CARDS[card]
    sym = spec["symbol"]

    k15 = next(x for x in paths if str(x).endswith("_15m.csv"))
    k1m = next(x for x in paths if str(x).endswith("_1m.csv"))
    raw15 = _load_kline(k15)
    raw1m = _load_kline(k1m)
    w0 = pd.Timestamp(WINDOW_START, tz="UTC")
    w1 = pd.Timestamp(WINDOW_END, tz="UTC")
    raw15 = raw15[(raw15.index >= w0) & (raw15.index < w1)]
    raw1m = raw1m[(raw1m.index >= w0) & (raw1m.index < w1)]
    if len(raw15) < 1000 or len(raw1m) < 1000:
        raise ValueError(f"window slice too small: 15m={len(raw15)} 1m={len(raw1m)}")

    cfg = FU.ConfigV2(
        fee_maker=0.0005, fee_taker=0.0005, slip_bps=0.5,   # repo 11 bps RT
        tick_size=spec["tick_size"], use_sessions=spec["use_sessions"],
        start_equity=START_EQ,
    )

    P = FS.prepare(raw15, cfg)
    S = FU.SessionContext(P, cfg, verbose=False)
    fine = FU.FineData(raw1m, P, cfg, verbose=False) if spec["fine"] else None

    # the pack's own parity contract (vector vs event, sessions ON, simple
    # mode) -- MEASURED, not asserted. The pack's parity_check_v2 FAILED on
    # the real slice (2023-01..2026-10): the two engines disagree on the
    # re-arm semantics after an unfilled order / a transient invalidation dip
    # (the vector restarts the touch sequence from its event-jump position;
    # the event engine walked the bars and saw touches the vector skipped).
    # The pack refuses its own numbers in that state ("fix before trusting").
    # This campaign publishes the EVENT engine (the production, live-ready
    # one) with the divergence measured trade-by-trade and DECLARED on every
    # artifact -- per the dated addendum in results/fvgup_pre_registration.md.
    simple = FU.replace(cfg, be_at_r=None, partial_at_r=None, partial_frac=0.0,
                        trail_at_r=None, min_notional=0.0, entry_delay_s=0.0,
                        manage_on_fine=False, flat_at_session_end=False,
                        max_daily_loss_pct=1.0, max_dd_stop_pct=1.0)
    vpar = FU.backtest_vector_v2(P, simple, S)
    epar = FU.EventEngineV2(P, simple, fine=None, sess=S).run()
    vi = set(vpar.entry_i.values.tolist()) if len(vpar) else set()
    ei = set(epar.entry_i.values.tolist()) if len(epar) else set()
    ev_only = epar[~epar.entry_i.isin(vi)].copy() if len(epar) else epar
    ve_only = vpar[~vpar.entry_i.isin(ei)].copy() if len(vpar) else vpar
    parity_ok = (len(vpar) == len(epar)) and len(ev_only) == 0 and len(ve_only) == 0

    def _div_rows(df, side):
        rows = []
        for r in df.itertuples(index=False):
            a = int(r.htf_id)
            rows.append([side, int(r.entry_i), str(r.entry_time), int(r.dir),
                         float(r.entry), float(r.stop), float(r.target),
                         a, int(P.htf_dir[a]) if 0 <= a < len(P.htf_dir) else -99,
                         float(P.htf_lo[a]) if 0 <= a < len(P.htf_lo) else 0.0,
                         float(P.htf_hi[a]) if 0 <= a < len(P.htf_hi) else 0.0])
        return rows
    par_rows = _div_rows(ev_only, "event_only") + _div_rows(ve_only, "vector_only")

    evt = FU.EventEngineV2(P, cfg, fine=fine, sess=S).run()
    stats = dict(evt.attrs.get("stats", {}))
    perf = FS.performance(evt, P, cfg)

    curve = evt.attrs["curve"]
    n_bars = int(P.n)
    net_ret_pct = float((curve.iloc[-1] / START_EQ - 1.0) * 100.0)

    # per-trade ex-cost decomposition (decision-identical by construction)
    if len(evt):
        gross_pnl = (evt.pnl + evt.fees + evt.funding).values
        pf_gross = _pf(gross_pnl)
        pf_net = _pf(evt.pnl.values)
        total_pnl = float(evt.pnl.sum())
        fees_total = float(evt.fees.sum())
        funding_total = float(evt.funding.sum())
        top5 = float(np.sort(evt.pnl.values)[::-1][:5].sum()) if len(evt) >= 5 \
            else total_pnl
        conc = float(top5 / total_pnl * 100.0) if total_pnl > 0 else None
        net_wo5 = net_ret_pct - (top5 / START_EQ * 100.0 if len(evt) >= 5 else 0.0)
        wins = evt[evt.pnl > 0].r.mean() if (evt.pnl > 0).any() else 0.0
        losses = evt[evt.pnl <= 0].r.mean() if (evt.pnl <= 0).any() else 0.0
        be_wr = (abs(losses) / (wins + abs(losses)) * 100.0) if (wins and losses) else None
    else:
        pf_gross = pf_net = None
        total_pnl = fees_total = funding_total = 0.0
        conc = None
        net_wo5 = net_ret_pct
        be_wr = None

    # identity for THIS pack's accounting: the entry fee is charged at open
    # OUTSIDE the trade pnl (the fees column includes it; pnl does not), and
    # funding is charged per 8h boundary outside pnl too:
    #   eq_final - start == sum(pnl) - sum(funding) - sum(entry*qty*fee_maker)
    # (partial and exit fees are already netted inside pnl). If a position is
    # still open at the last bar the pack does not force-close it; the mark
    # residual is then DECLARED (open_position_residual), never assumed zero.
    entry_fees = float((evt.entry * evt.qty * cfg.fee_maker).sum()) if len(evt) else 0.0
    open_resid = 0.0
    if len(evt):
        resid = float(curve.iloc[-1] - START_EQ - total_pnl + funding_total
                      + entry_fees)
    else:
        resid = float(curve.iloc[-1] - START_EQ)
    flat_at_end = bool(len(evt)) and abs(float(curve.iloc[-1])
                                         - float(evt.equity.iloc[-1])) < 1e-9
    if not flat_at_end and len(evt):
        open_resid = resid
        resid = 0.0
    if abs(resid) > 1e-6 * START_EQ:
        raise AssertionError(f"accounting invariant broken: residual {resid}")

    # window stats: thirds / halves / OOS 70/30 on the full bar range (the book
    # trades from the start of the window; no late-start problem here)
    n = len(curve)
    thirds, halves = [], []
    for c in range(3):
        a, b = n * c // 3, n * (c + 1) // 3
        base = curve.iloc[a - 1] if a > 0 else START_EQ
        thirds.append(float((curve.iloc[b - 1] / base - 1.0) * 100.0))
    for c in range(2):
        a, b = n * c // 2, n * (c + 1) // 2
        base = curve.iloc[a - 1] if a > 0 else START_EQ
        halves.append(float((curve.iloc[b - 1] / base - 1.0) * 100.0))
    split = int(n * 0.7)
    is_ret = float((curve.iloc[split] / START_EQ - 1.0) * 100.0)
    oos_ret = float((curve.iloc[-1] / curve.iloc[split] - 1.0) * 100.0)
    if len(evt):
        is_tr = evt[evt.exit_i < split]
        oos_tr = evt[evt.exit_i >= split]
        is_pf = _pf(is_tr.pnl.values) if len(is_tr) else None
        oos_pf = _pf(oos_tr.pnl.values) if len(oos_tr) else None
        is_n, oos_n = int(len(is_tr)), int(len(oos_tr))
    else:
        is_pf = oos_pf = None
        is_n = oos_n = 0

    # yearly (calendar) returns of the book
    years = sorted(set(curve.index.year))
    yearly = {}
    for y in years:
        sub = curve[curve.index.year == y]
        first_pos = curve.index.get_loc(sub.index[0])
        base = curve.iloc[first_pos - 1] if first_pos > 0 else START_EQ
        yearly[str(y)] = float((sub.iloc[-1] / base - 1.0) * 100.0)
    green_years = sum(1 for v in yearly.values() if v > 0)

    bh_ret = float((raw15.close.iloc[-1] / raw15.close.iloc[0] - 1.0) * 100.0)

    dd = float(perf.get("max_dd_pct", 0.0))
    win_rate = _finite(perf.get("win_rate_pct"))

    # ---- gates (screen battery, measured here so the report can cite them) ----
    gates = []
    g = gates.append
    g(["pf_ex_cost_gt_1.2", ">1.2", _finite(pf_gross), pf_gross is not None and pf_gross > 1.2])
    g(["n_trades_ge_30", ">=30", int(len(evt)), len(evt) >= 30])
    g(["oos_pf_ge_1", ">=1 (OOS PF < 1 = KILL)", _finite(oos_pf),
       oos_pf is not None and oos_pf >= 1.0])
    g(["green_years_frac", ">=2/3 years green", f"{green_years}/{len(years)}",
       len(years) >= 3 and green_years / len(years) >= 2.0 / 3.0])
    g(["conc_top5_lt_100", "<100% of PnL", _finite(conc),
       conc is not None and conc < 100.0])
    g(["net_without_top5_pos", ">0%", float(net_wo5), net_wo5 > 0.0])
    g11 = True
    if win_rate is not None and win_rate >= 75.0:
        g11 = be_wr is not None and win_rate >= be_wr + 5.0
    g(["g11_winrate_buffer", "wr>=75 needs wr>=breakeven+5pp", _finite(be_wr), g11])
    g(["beats_bh", f"net > B&H ({bh_ret})", net_ret_pct > bh_ret, bool(net_ret_pct > bh_ret)])
    # JSON hygiene: numpy bool/float leak into the gate rows through
    # comparisons on numpy scalars -- serialize only python types
    gates = [[r[0], r[1],
              float(r[2]) if isinstance(r[2], (np.floating, np.integer)) else r[2],
              bool(r[3])] for r in gates]
    all_pass = all(r[3] for r in gates)
    flag = "PASS" if all_pass else "FAIL-GATES:" + ",".join(r[0] for r in gates if not r[3])

    fine_stats = dict(fine.stats) if spec["fine"] and fine is not None else None

    metrics = {
        "flag": flag,
        "card": card, "symbol": sym,
        "parity_ok": parity_ok,
        "parity_vector_n": int(len(vpar)),
        "parity_event_n": int(len(epar)),
        "n_event_only_trades": int(len(ev_only)),
        "n_vector_only_trades": int(len(ve_only)),
        "fill_model": "maker_limit_1m_resolved" if spec["fine"] else "coarse_15m_same_bar",
        "certifiable": bool(spec["fine"]),
        "fee_maker": 0.0005, "fee_taker": 0.0005, "slip_bps": 0.5,
        "cost_rt_taker_bps": 11.0, "cost_rt_maker_bps": 10.5,
        "funding_model": "pack constant 1.0 bp per 8h (longs pay) — approximation, declared",
        "window_start": WINDOW_START, "window_end": WINDOW_END,
        "n_bars_15m": int(n_bars), "n_bars_1m": int(len(raw1m)),
        "n_trades": int(len(evt)),
        "return_pct": net_ret_pct,
        "profit_factor": _finite(pf_net),
        "profit_factor_ex_cost": _finite(pf_gross),
        "win_rate": win_rate,
        "expectancy_r": _finite(perf.get("expectancy_r")),
        "sharpe_annualised": _finite(perf.get("sharpe")),
        "max_dd_pct": dd,
        "bh_return_pct": bh_ret,
        "fees_total_usdt": fees_total,
        "funding_total_usdt": funding_total,
        "pnl_identity_resid": resid,
        "entry_fees_total_usdt": entry_fees,
        "open_position_residual": float(open_resid),
        "is_return_pct": is_ret, "oos_return_pct": oos_ret,
        "is_pf": _finite(is_pf), "oos_pf": _finite(oos_pf),
        "is_n": is_n, "oos_n": oos_n,
        "thirds": [round(x, 6) for x in thirds], "halves": [round(x, 6) for x in halves],
        "green_years": int(green_years), "n_years": len(years),
        "conc_top5_share_pct": _finite(conc),
        "conc_net_without_top5_pct": float(net_wo5),
        "breakeven_win_rate": _finite(be_wr),
        "engine_stats": {k: int(v) for k, v in stats.items()},
        "fine_pct_usable": _finite(fine_stats.get("pct_usable")) if fine_stats else None,
        "sessions_on": bool(spec["use_sessions"]),
        "tick_size": spec["tick_size"],
        "start_equity": START_EQ,
    }

    def _trow(r):
        return dict(
            entry_time=str(r.entry_time), exit_time=str(r.exit_time),
            dir=int(r.dir), entry=float(r.entry), exit=float(r.exit),
            stop=float(r.stop), target=float(r.target), bars=int(r.bars),
            reason=str(r.reason), pnl=float(r.pnl), fees=float(r.fees),
            funding=float(r.funding), r=float(r.r),
            sid_entry=int(r.sid_entry), sid_setup=int(r.sid_setup))

    tables = {
        "yearly": [[y, yearly[y]] for y in sorted(yearly)],
        "thirds_halves": [["third1", thirds[0]], ["third2", thirds[1]],
                          ["third3", thirds[2]], ["half1", halves[0]],
                          ["half2", halves[1]]],
        "gates": gates,
        "parity_divergence": par_rows,
        "session_attribution": _session_table(evt),
        "trades": [_trow(r) for r in evt.itertuples(index=False)],
    }

    prov = {
        "engine_version": ENGINE_VERSION,
        "sources_of_record": ["code/fvg_system.py", "code/fvg_upgrades.py"],
        "pre_registration": "results/fvgup_pre_registration.md",
        "conventions": {
            "strategy": "ICT 4H FVG -> 15M FVG entry: a 4H FVG zone (point-in-time "
                        "map, knowable at 4H close) is touched on 15m; a 15m FVG "
                        "confirming within max_wait must print; LIMIT order at the "
                        "15m FVG proximal edge (expiry 8 bars), stop beyond the FVG "
                        "+ 0.25 ATR, TP 2R, BE at 1R, 50% partial at 1R, trail from "
                        "2R (ATR 2), 24h time stop, one trade per 4H zone",
            "costs": "repo regime injected by caller: fee 5 bps + slip 0.5 bps per "
                     "side = 11 bps RT on taker exits / 10.5 maker; charged on "
                     "every fill; entries/targets maker, stop/time/gap taker",
            "funding": "pack's own constant-rate model (1 bp per 8h, longs pay / "
                       "shorts receive), billed per 8h boundary while held — an "
                       "approximation declared in the pre-registration; real per-"
                       "settlement funding files are NOT wired (engine not editable)",
            "pf_ex_cost": "per-trade decomposition gross = pnl + fees + funding "
                          "from the SAME run — decision-identical by construction "
                          "(a zero-fee re-run would move the pack's break-even "
                          "stop and thus decisions)",
            "parity": "MEASURED, FAILED, DECLARED: parity_check_v2's "
                      "simple-mode engines disagree on the real slice (the "
                      "vector restarts a zone's touch sequence from its "
                      "event-jump position; the event engine walks every bar "
                      "and saw touches the vector skipped). The divergence is "
                      "measured trade-by-trade (parity_divergence table) and "
                      "this artifact publishes the EVENT engine only -- the "
                      "pack's dual-engine verification does NOT hold until "
                      "the author reconciles the re-arm semantics",
            "invariant": "eq_final - start == sum(pnl) - sum(funding) - "
                         "sum(entry*qty*fee_maker): the pack charges the ENTRY "
                         "fee at open OUTSIDE the trade pnl (the fees column "
                         "includes it, pnl does not) and funding per 8h "
                         "boundary outside pnl; partial/exit fees are netted "
                         "inside pnl. residual asserted <= 1e-6 of equity; if "
                         "a position is open at the last bar (the pack does "
                         "not force-close) the mark residual is declared as "
                         "open_position_residual, never assumed zero",
            "window": "both inputs sliced to [2023-01-01, 2026-10-01) = the 1m "
                      "coverage; every 15m bar is 1m-resolvable",
            "fine_integrity": "FineData aggregates the 1m tape per 15m bar and "
                              "compares OHLC vs the 15m bar (tol 0.5 bps); "
                              "fine_strict demands 15 complete matching minutes",
            "certifiability": "fine cells: maker limit fills resolved on the 1m "
                              "tape -> certifiable per the fill-model rule; "
                              "coarse cell: 15m same-bar convention -> declared "
                              "NOT certifiable comparison",
            "sessions": "SessionContext: London 02:00-05:00 + NY-AM 08:30-11:00 "
                        "America/New_York, weekends skipped, pending orders "
                        "cancelled at the first blocked bar; risk logic never "
                        "session-gated (pack rule)",
        },
    }
    return metrics, prov, tables


def _session_table(evt):
    """The pack's session attribution: which killzone pays (upgrade #2)."""
    if not len(evt) or "sid_entry" not in evt:
        return []
    names = FU.SESSION_NAMES
    rows = []
    for sid, grp in evt.groupby("sid_entry"):
        pnl = grp.pnl
        gp = pnl[pnl > 0].sum()
        gl = -pnl[pnl <= 0].sum()
        rows.append([names.get(int(sid), str(sid)), int(len(grp)),
                     float(100 * (pnl > 0).mean()), float(grp.r.mean()),
                     float(pnl.sum()),
                     float(gp / gl) if gl > 0 else None])
    rows.sort(key=lambda r: -r[4])
    return rows
