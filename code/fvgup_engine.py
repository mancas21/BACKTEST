"""fvgup_engine.py — adapter engine for the fvg_system + fvg_upgrades pack
(2026-11-13). Sources of record, byte-identical from the attachments:
  * code/fvg_system.py  — base ICT 4H FVG -> 15M FVG system (vector + event
    engines, parity contract, setup logic, cost model)
  * code/fvg_upgrades.py — extensions: 1m intrabar fill resolution (FineData
    with vectorized integrity audit), DST-correct session/killzone + liquidity
    filters (SessionContext), EventEngineV2.

Repo integration, all DECLARED (nothing edited in the pack):
  * costs injected by the caller: fee_maker = fee_taker = 0.0005 (5 bps per
    side) + slip_bps 0.5 (adverse, taker exits) -> 11 bps round trip on taker
    exits / 10.5 on maker exits;
  * funding stays at the pack's own CONSTANT-rate model (funding_bps_8h=1.0:
    longs pay, shorts receive) — an approximation; the repo's real per-
    settlement funding files are NOT used because the pack bills a constant
    rate inside its engine and the engine is not editable. fees_total and
    funding_total are measured inside the artifact;
  * PF ex-cost is computed PER TRADE from the same run: gross_pnl = pnl +
    fees + funding — decision-identical by construction (the pack's break-even
    stop depends on fee levels, so a zero-fee re-run would NOT be
    decision-identical; the per-trade decomposition is);
  * window: both inputs sliced to the 1m-covered window [2023-01-01,
    2026-10-01) so every 15m bar is 1m-resolvable (fine_strict);
  * parity: the pack's own parity_check_v2 (vector vs event engine, sessions
    ON, simple mode) must MATCH on the real slice inside every artifact — the
    artifact refuses to exist otherwise;
  * accounting invariant asserted: equity_final - start == sum(pnl) -
    sum(funding) (the pack charges funding outside the trade pnl); the
    residual is published as pnl_identity_resid;
  * certifiability: fine cells resolve maker limit fills on the 1m tape (the
    fill-model rule's demanded 1m resolution) -> certifiable; the coarse cell
    uses the 15m same-bar convention -> declared NOT certifiable comparison.

Cards (card_from_symbol): BTCFINE (BTCUSDT, fine, sessions on),
BTCCOARSE (BTCUSDT, no fine, sessions on), BTCNOSESS (BTCUSDT, fine, sessions
off), ETHFINE (ETHUSDT, fine, sessions on, tick_size 0.01).
"""

import json
